def make_keigo_pair(idx: int, domain: str, high: str, low: str) -> HonorificPair:
    from src.data.confounds import strip_pronouns
    return HonorificPair(
        id=f"jp_{idx:04d}",
        high=high,
        low=low,
        high_level="aap",
        low_level="tu",
        domain=domain,
        confounds={
            "pronoun_stripped_high": strip_pronouns(high),
            "pronoun_stripped_low": strip_pronouns(low),
        },
        notes="teineigo vs. plain-form Japanese keigo contrast",
    )


def main() -> None:
    pairs = [make_keigo_pair(i, d, h, l) for i, (d, h, l) in enumerate(TEMPLATES)]
    assert len(pairs) == 200, f"Expected 200 pairs, got {len(pairs)}"
    save_dataset(pairs, "data/japanese/keigo_200.json")
    from collections import Counter
    counts = Counter(p.domain for p in pairs)
    print(f"Saved {len(pairs)} pairs to data/japanese/keigo_200.json")
    for domain, count in sorted(counts.items()):
        print(f"  {domain}: {count}")


if __name__ == "__main__":
    main()
